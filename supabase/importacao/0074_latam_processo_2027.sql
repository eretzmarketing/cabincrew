<p>A LATAM é a maior companhia aérea da América Latina, com voos nacionais e internacionais. As seleções de comissários têm muitos inscritos e usam <strong>ranking</strong> em várias etapas: a meta não é só "passar", é ficar entre os melhores.</p>

<h3>Requisitos obrigatórios (processo 2027)</h3>
<ul>
<li>Ter 18 anos ou mais.</li>
<li>Ser brasileiro(a) nato(a) ou naturalizado(a).</li>
<li>Ensino médio completo.</li>
<li>CMA (Certificado Médico Aeronáutico) com <strong>pelo menos 1 ano de validade no dia da inscrição</strong>.</li>
<li>Curso profissionalizante de comissário de voo. Podem participar candidatos com ou sem o CCT, com ou sem experiência na função.</li>
<li><strong>Imprescindível:</strong> experiência de trabalho com serviços, atendimento ao cliente e/ou vendas.</li>
</ul>

<h3>Outros requisitos e diferenciais</h3>
<ul>
<li><strong>Carência de 6 meses</strong> entre uma candidatura e outra.</li>
<li><strong>Passaporte brasileiro</strong> com pelo menos 2 anos de validade, a partir da entrevista com RH e gestão.</li>
<li><strong>CIVP</strong> (certificado internacional de vacinação contra febre amarela) na admissão.</li>
<li><strong>Diferenciais:</strong> inglês e/ou espanhol validados pela metodologia ICAO nível 4; carteira de A320 ou de Embraer E2; e <strong>aprovação na prova teórica da ANAC já no momento da inscrição</strong>.</li>
</ul>

<h3>As etapas, na ordem</h3>
<ol>
<li><strong>Inscrição</strong> no site de carreiras da LATAM e preenchimento do formulário <strong>Dados Iniciais</strong> no Portal do Candidato. Os dois são obrigatórios e têm prazo.</li>
<li><strong>Triagem inicial</strong> dos dados informados. Eles são conferidos durante todo o processo: informação errada ou faltando pode eliminar.</li>
<li><strong>Testes online na plataforma Vora</strong> (a evolução da antiga JobCoach): competências comportamentais e valores pessoais, conhecimento técnico e português, todos <strong>eliminatórios</strong> e com ranking; inglês e espanhol <strong>não eliminam</strong>, apenas mapeiam o seu nível.</li>
<li><strong>Dinâmica em grupo</strong>, presencial ou online. Cada pessoa é avaliada individualmente.</li>
<li><strong>Entrevista individual com RH e gestor de tripulação</strong>, presencial, numa base da LATAM que você escolhe, somente com convocação nominal.</li>
<li><strong>Testes na plataforma SHL</strong>: avaliação comportamental, psicométrica e de raciocínio dedutivo, todas eliminatórias.</li>
<li><strong>Avaliação de idiomas pela metodologia ICAO</strong>, presencial ou online, para quem foi bem nos testes de inglês e/ou espanhol.</li>
<li><strong>Documentos e exames</strong>: fichas cadastrais, envio de documentos pela plataforma Unico People e exames toxicológico e admissional.</li>
<li><strong>Validação final e proposta de trabalho</strong>, por e-mail, com prazo para aceitar.</li>
<li><strong>Treinamento</strong> na academia da LATAM em São Paulo (cerca de 80 dias corridos, a maior parte presencial), instrução em rota, check de competência e, enfim, os primeiros voos.</li>
</ol>
<p>Dependendo da cidade, a LATAM pode fazer um <strong>Assessment Day</strong>: dinâmica, entrevista, exames e avaliação de idiomas no mesmo dia.</p>

<h3>Regras que mais eliminam (atenção!)</h3>
<ul>
<li><strong>Um e-mail só, do começo ao fim.</strong> Todas as convocações chegam no e-mail da inscrição, e usar outro e-mail em qualquer etapa desclassifica. Use um e-mail que você acessa sempre (a LATAM recomenda Gmail) e olhe também o Spam e o Lixo eletrônico.</li>
<li><strong>Prazos:</strong> não fazer um teste dentro do prazo do seu grupo conta como desistência.</li>
<li><strong>Prova monitorada:</strong> nos testes da Vora, a câmera e o microfone ficam ligados e o sistema percebe cliques fora da página, consultas e ajuda de outras pessoas. <strong>Fone de ouvido e óculos inteligentes podem ser considerados fraude.</strong> Teste câmera e microfone antes.</li>
<li><strong>Faltou à dinâmica ou à entrevista?</strong> Só existe segunda chamada para quem avisou antes, com justificativa, pelo Fale Conosco do Portal do Candidato. A segunda chamada da entrevista é presencial em São Paulo.</li>
<li><strong>Dinheiro:</strong> a LATAM nunca pede pagamento para participar da seleção. Desconfie de qualquer mensagem que peça dinheiro "para garantir a vaga".</li>
</ul>

<h3>O peso do idioma</h3>
<p>No processo 2027, <strong>50% das vagas</strong> vão para quem tira <strong>nota ICAO 4 ou mais em inglês e/ou espanhol</strong>. Os testes de idioma da Vora não eliminam ninguém, mas são eles que definem quem é chamado para a avaliação ICAO. Na prática, quem tem idioma disputa metade das vagas com muito menos concorrentes.</p>

<h3>Ranking, convocação e espera</h3>
<p>As notas formam um ranking. Os melhores são chamados na <strong>1ª convocação</strong>; os demais podem ficar em lista de espera por até 12 meses e ser chamados na <strong>2ª convocação</strong>, conforme a necessidade de contratação. Todas as etapas são eliminatórias até o aceite da proposta, inclusive os exames.</p>

<h3>Como se preparar para a LATAM com o Head Hunter</h3>
<ul>
<li><strong>Vora:</strong> faça os simulados da banca ANAC no modo <strong>Prova real</strong> (sem sair da página), treine português até passar de 80% com folga e faça o perfil comportamental algumas vezes, cuidando da coerência.</li>
<li><strong>Dinâmica e entrevista:</strong> estude os módulos de Dinâmicas de Grupo, Entrevistas e Atendimento, e grave o vídeo de apresentação para treinar como você fala de si.</li>
<li><strong>SHL:</strong> treine raciocínio dedutivo, numérico, verbal e julgamento situacional. O convite pode chegar com pouco prazo.</li>
<li><strong>Idioma:</strong> comece o inglês (ou o espanhol) desde o primeiro dia.</li>
<li><strong>Organização:</strong> separe CMA, passaporte e CIVP com antecedência e planeje a sua ida para São Paulo no treinamento (passagem e moradia por sua conta; a companhia pode oferecer passe aéreo, sujeito a lugar no voo).</li>
<li>Leia o edital inteiro assim que ele sair no Portal do Candidato: as regras mudam de um processo para outro.</li>
</ul>
