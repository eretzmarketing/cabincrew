        "insert into opq_afirmacoes (codigo, traco, direcao, texto, ativo, origem) values",
        ",\n".join(f"({q(c)}, {q(t)}, {d}, {q(x)}, {'true' if a else 'false'}, {q(o)})" for c, t, d, x, a, o in linhas),
